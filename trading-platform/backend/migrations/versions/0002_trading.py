def _app_role() -> str:
    role = os.environ.get("DB_APP_ROLE", "tp_app")
    if not re.fullmatch(r"[a-z_][a-z0-9_]{0,62}", role):
        raise RuntimeError("DB_APP_ROLE must be a plain lower-case PostgreSQL role name")
    return role


